CREATE DATABASE IF NOT EXISTS TaskManagerDB;
GO

USE TaskManagerDB;
GO

CREATE TABLE IF NOT EXISTS Users (
    UserId INT IDENTITY(1, 1) PRIMARY KEY,
    FullName NVARCHAR(100) NOT NULL,
    Email NVARCHAR(150) NOT NULL UNIQUE,
    PasswordHash NVARCHAR(255) NOT NULL,
    CreatedAt DATETIME NOT NULL DEFAULT SYSUTCDATETIME()
);
GO

CREATE TABLE IF NOT EXISTS Projects (
    ProjectId INT IDENTITY(1, 1) PRIMARY KEY,
    ProjectName NVARCHAR(150) NOT NULL,
    Description NVARCHAR(500) NOT NULL,
    OwnerId INT NOT NULL,
    Deadline DATETIME2 NOT NULL,
    Status NVARCHAR(20) NOT NULL DEFAULT 'Active'
        CONSTRAINT CK_Projects_Status CHECK (STATUS IN ('Active', 'On Hold', 'Completed')),
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_Projects_Owner FOREIGN KEY (OwnerId) REFERENCES User(UserId)
);
GO

CREATE TABLE IF NOT EXISTS TASKS (
    TaskId INT IDENTITY(1, 1) PRIMARY KEY,
    ProjectId INT NOT NULL,
    AssigneeId INT NULL,
    ParentTaskId INT NULL,
    Title NVARCHAR(200) NOT NULL,
    Description NVARCHAR(1000) NULL,
    Priority NVARCHAR(20) NOT NULL DEFAULT 'Medium'
    CONSTRAINT CK_Tasks_Priority CHECK (Priority IN ('Low', 'Medium', 'High', 'Critical')),
    Status NVARCHAR(20) NOT NULL DEFAULT 'To Do'
    CONSTRAINT CK_Tasks_Status CHECK (Status IN ('To Do', 'In Progress', 'In Review', 'Done')),
    DueDate DATETIME2 NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_Tasks_Project FOREIGN KEY (ProjectId) REFERENCES Projects(ProjectId) ON DELETE CASCADE,
    CONSTRAINT FK_Tasks_Assignee FOREIGN KEY (AssigneeId) REFERENCES Users(UserId) ON DELETE SET NULL,
    CONSTRAINT FK_TASKS_ParentTask FOREIGN KEY (ParentTaskId) REFERENCES Tasks(TaskId)
);
GO

CREATE TABLE IF NOT EXISTS Tags (
    TagId INT IDENTITY(1, 1) NOT NULL,
    TagName NVARCHAR(50) NOT NULL UNIQUE,
    ColorHex NVARCHAR(7) NOT NULL DEFAULT '#6366F1'
);
GO

CREATE TABLE IF NOT EXISTS TaskTags(
    TaskId INT NOT NULL,
    TagId INT NOT NULL,
    CONSTRAINT PK_TaskTags PRIMARY KEY (TaskId, TagId),
    CONSTRAINT FK_TaskTags_Task FOREIGN KEY (TaskId) REFERENCES Tasks(TaskId) ON DELETE CASCADE,
    CONSTRAINT FK_TaskTags_Tag FOREIGN KEY (TagId) REFERENCES Tags(TagId) ON DELETE CASCADE
);
GO

CREATE TABLE IF NOT EXISTS TaskComments (
    CommentId INT IDENTITY(1,1) PRIMARY KEY,
    TaskId INT NOT NULL,
    UserId INT NOT NULL,
    CommentText NVARCHAR(1000) NOT NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_TaskComments_Task FOREIGN KEY (TaskId) REFERENCES Tasks(TaskId) ON DELETE CASCADE,
    CONSTRAINT FK_TaskComments_User FOREIGN KEY (UserId) REFERENCES Users(UserId)
);
GO

CREATE TABLE IF NOT EXISTS TaskAuditLogs (
    LogId INT IDENTITY(1,1) PRIMARY KEY,
    TaskId INT NOT NULL,
    FieldChanged NVARCHAR(50) NOT NULL,
    OldValue NVARCHAR(200) NULL,
    NewValue NVARCHAR(200) NULL,
    ChangedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_TaskAuditLogs_Task FOREIGN KEY (TaskId) REFERENCES Tasks(TaskId) ON DELETE CASCADE
);
GO

-- Non-Clustered Indexes for Query Performance
CREATE NONCLUSTERED INDEX IX_Tasks_ProjectId_Status ON Tasks(ProjectId, Status);
CREATE NONCLUSTERED INDEX IX_Tasks_AssigneeId ON Tasks(AssigneeId);
CREATE NONCLUSTERED INDEX IX_TaskAuditLogs_TaskId ON TaskAuditLogs(TaskId);
GO